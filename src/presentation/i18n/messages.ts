const MESSAGES: Record<SupportedUiLocale, Dict> = { en, de, es, fr, zh };

export function translate(
  locale: SupportedUiLocale,
  key: string,
  params?: Record<string, string | number>,
): string {
  const template = MESSAGES[locale]?.[key] ?? MESSAGES.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    name in params ? String(params[name]) : `{${name}}`,
  );
}

/** Bound translator for a fixed locale — convenient in components. */
export function translatorFor(locale: SupportedUiLocale): (key: string, params?: Record<string, string | number>) => string {
  return (key, params) => translate(locale, key, params);
}
